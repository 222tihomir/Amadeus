function formatAgo(ms) {
  const min = Math.round(ms / 60000);
  if (min < 2) return null;
  if (min < 60) return `${min} мин`;
  const h = Math.round(min / 60);
  if (h < 48) return `${h} ч`;
  return `${Math.round(h / 24)} дн`;
}

