const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('amadeus', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  chat: (req) => ipcRenderer.invoke('chat:send', req),
  speak: (text, emotion, seed) => ipcRenderer.invoke('tts:speak', { text, emotion, seed }),
  speakReply: (segments) => ipcRenderer.invoke('tts:speak-reply', { segments }),
  transcribe: (audio, mime) => ipcRenderer.invoke('stt:transcribe', { audio, mime }),
  listVoices: () => ipcRenderer.invoke('voices:list'),
  opencodeModels: () => ipcRenderer.invoke('opencode:models'),
  getHistory: () => ipcRenderer.invoke('history:get'),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  getMemory: () => ipcRenderer.invoke('memory:get'),
  clearMemory: () => ipcRenderer.invoke('memory:clear'),
  visionAvailable: () => ipcRenderer.invoke('vision:available'),
  webStatus: (site) => ipcRenderer.invoke('web:status', site),
  webLoginHere: (site) => ipcRenderer.invoke('web:loginHere', site),
  webLoginBrowser: (site, browser) => ipcRenderer.invoke('web:loginBrowser', { site, browser }),
  webTransferLogin: (site) => ipcRenderer.invoke('web:transferLogin', site),
  webLoginOpen: (site) => ipcRenderer.invoke('web:loginOpen', site),
  webDefaultBrowser: () => ipcRenderer.invoke('web:browsers'),
  webToggle: (site) => ipcRenderer.invoke('web:toggle', site),
  onWebLoginStatus: (cb) => ipcRenderer.on('web:loginStatus', (_, msg) => cb(msg)),
  getSummary: () => ipcRenderer.invoke('summary:get'),
  defaultPersona: () => ipcRenderer.invoke('persona:default'),
  runAction: (id) => ipcRenderer.invoke('tools:run', id),
  denyAction: (id) => ipcRenderer.invoke('tools:deny', id),
  minimize: () => ipcRenderer.send('win:minimize'),
  close: () => ipcRenderer.send('win:close'),
  fullscreen: () => ipcRenderer.invoke('win:toggle-fullscreen'),
  onMicToggle: (cb) => ipcRenderer.on('mic:toggle', cb),
});
